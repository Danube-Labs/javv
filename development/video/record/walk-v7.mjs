// Video 7, build a dashboard: make it, add panels, move one, change one, add Triage activity,
// delete a panel, save, read it, copy it with export and import, delete the copy, and open the
// dashboard as a viewer. The walk makes a new dashboard each time, so it runs on any store; run
// it after the walks of videos 2 to 4, so that Triage activity has changes to show.
import fs from 'node:fs'
import path from 'node:path'
import { BASE, STATE, record, sleep } from './common.mjs'

const NAME = 'Platform team'
// tall enough for the whole dashboard: a drag that scrolls the page moves the sticky save bar
// into the middle of a full-page shot
const VIEW = { width: 1440, height: 1500 }

await record('v7', async ({ page: first, shot, hoverShot, settle, switchUser }) => {
  let page = first
  const dialog = () => page.getByRole('dialog').first()
  const head = () => page.locator('.head-actions')
  const headBtn = (name) => head().getByRole('button', { name, exact: true })
  const tab = (panel) => page.locator('.grid-stack-item').filter({ has: page.getByRole('button', { name: `Move ${panel}`, exact: true }) })
  const readPanel = (id) => page.locator(`[data-panel="${id}"]`).first()
  const popover = (title) => page.locator('.pop').filter({ has: page.locator('.pop-head', { hasText: title }) }).first()
  const card = (id) => page.locator('.view-card').filter({ has: page.locator(`a[href="/dashboards/${id}"]`) }).first()
  /** waits for the panels to load: no skeleton left on the page */
  async function loaded() {
    await page.waitForFunction(() => !document.querySelector('.skel'), null, { timeout: 20000 }).catch(() => {})
    await settle()
  }
  /** a pick in the filter list of a settings window (`bar`), then the list closes */
  async function pickFilter(bar, field, value, prefix) {
    const add = bar.locator('.add-filter')
    await shot(`${prefix}-bar`, { pop: bar, add })
    await hoverShot(`${prefix}-bar`, add)
    await add.click()
    await settle()
    const fieldRow = page.locator('.filter-field').filter({ hasText: new RegExp(`^\\s*${field}`) })
    await shot(`${prefix}-fields`, { pop: bar, menu: page.locator('.filter-menu'), field: fieldRow })
    await hoverShot(`${prefix}-fields`, fieldRow)
    await fieldRow.click()
    await settle()
    const valueRow = page.locator('.filter-menu .facet-row').filter({ hasText: value }).first()
    await valueRow.waitFor({ timeout: 10000 })
    await shot(`${prefix}-values`, { pop: bar, menu: page.locator('.filter-menu'), value: valueRow })
    await hoverShot(`${prefix}-values`, valueRow)
    await valueRow.click()
    await settle()
    await page.keyboard.press('Escape')
    await settle()
  }

  await page.goto(`${BASE}/dashboards?cluster=prod-eu-1`)
  await page.getByRole('heading', { name: 'Dashboards' }).waitFor({ timeout: 20000 })
  await settle()
  const create = page.getByRole('button', { name: 'New dashboard' }).first()
  await shot('list', { create, nav: page.getByRole('link', { name: 'Dashboards' }).first() })
  await hoverShot('list', create)

  // 1. the details window: name, sharing, the role, Create
  await create.click()
  await dialog().waitFor({ timeout: 10000 })
  await settle()
  const name = dialog().locator('#dash-name')
  const someRoles = dialog().getByRole('button', { name: 'Some roles' })
  await shot('details', { dialog: dialog(), name })
  await name.click()
  const letters = NAME.split(' ')
  for (let i = 1; i <= letters.length; i++) {
    await name.fill(letters.slice(0, i).join(' '))
    await page.mouse.move(5, 5)
    await sleep(60)
    await shot(`type-${i}`)
  }
  await shot('named', { dialog: dialog(), someRoles })
  await hoverShot('named', someRoles)
  await someRoles.click()
  const roles = dialog().getByRole('group', { name: 'Roles that can see the dashboard' })
  await roles.waitFor({ timeout: 10000 })
  await settle()
  const viewer = roles.getByRole('button', { name: /^viewer$/i })
  await shot('roles', { dialog: dialog(), roles, viewer })
  await hoverShot('roles', viewer)
  await viewer.click()
  await settle()
  const opensOn = dialog().getByRole('group', { name: 'Opens on' })
  const createBtn = dialog().getByRole('button', { name: 'Create' })
  await shot('roles-on', { dialog: dialog(), opensOn, createBtn })
  await hoverShot('roles-on', createBtn)
  await createBtn.click()
  // the empty dashboard has a second Add panel button; the walk uses the one in the head
  const addPanel = headBtn('Add panel')
  await addPanel.waitFor({ timeout: 15000 })
  await settle()
  const dashUrl = page.url().split('?')[0]
  const dashId = dashUrl.split('/').pop()

  // 2. the catalog: pick a panel, see its preview, add it; then two more
  await shot('empty', { addPanel })
  await hoverShot('empty', addPanel)
  /** opens the catalog, picks the panel and adds it; `first` shows the catalog before the pick */
  async function addFromCatalog(panel, prefix, { first = false, last = false } = {}) {
    await addPanel.click()
    const cat = dialog()
    await cat.waitFor({ timeout: 10000 })
    await settle()
    const row = cat.locator('.cat-row').filter({ hasText: panel })
    if (first) {
      await shot('catalog', { cat, row, list: cat.locator('.cat-list') })
      await hoverShot('catalog', row)
    }
    await row.click()
    await loaded()
    const add = cat.getByRole('button', { name: 'Add panel' })
    await shot(`${prefix}-picked`, { cat, preview: cat.locator('.cat-detail'), opts: cat.locator('.cat-opts'), add })
    await hoverShot(`${prefix}-picked`, add)
    await add.click()
    await cat.waitFor({ state: 'detached', timeout: 10000 })
    await loaded()
    await shot(`${prefix}-added`, { addPanel, grid: page.locator('.grid-stack'), added: page.locator(`.grid-stack-item[data-panel]`).last() })
    if (!last) await hoverShot(`${prefix}-added`, addPanel)
  }
  const panels = ['Findings summary', 'Findings by namespace', 'Top components']
  for (const [i, panel] of panels.entries()) await addFromCatalog(panel, `p${i + 1}`, { first: i === 0, last: i === panels.length - 1 })

  // 3. drag the last half panel to the free column at the right of the one above it
  const grid = page.locator('.grid-stack')
  const move = page.getByRole('button', { name: `Move ${panels[2]}`, exact: true })
  await shot('before-drag', { move, grid })
  await hoverShot('before-drag', move)
  const from = await move.boundingBox()
  const start = { x: from.x + from.width / 2, y: from.y + from.height / 2 }
  const beside = await tab(panels[1]).boundingBox()
  const end = { x: start.x + beside.width, y: beside.y + 20 }
  await page.mouse.move(start.x, start.y)
  await page.mouse.down()
  const steps = 6
  for (let i = 1; i <= steps; i++) {
    await page.mouse.move(start.x + ((end.x - start.x) * i) / steps, start.y + ((end.y - start.y) * i) / steps, { steps: 4 })
    await sleep(150)
    await shot(`drag-${i}`)
  }
  await page.mouse.up()
  await settle()
  await shot('dropped', { moved: page.getByRole('button', { name: `Move ${panels[2]}`, exact: true }), grid })

  // 4. the settings of one panel: Height, a pinned scanner, and a filter. Top components has more
  // rows than a short panel shows, so Tall shows more of them
  const nsSettings = page.getByRole('button', { name: `Settings of ${panels[2]}`, exact: true })
  await shot('settings-btn', { settings: nsSettings, panel: tab(panels[2]) })
  await hoverShot('settings-btn', nsSettings)
  await nsSettings.click()
  const settingsBox = popover('Panel settings')
  await settingsBox.waitFor({ timeout: 10000 })
  await settle()
  const tall = settingsBox.getByRole('group', { name: 'Height' }).getByRole('button', { name: 'Tall' })
  await shot('settings', { pop: settingsBox, tall })
  await hoverShot('settings', tall)
  await tall.click()
  await settle()
  const trivy = settingsBox.getByRole('group', { name: 'Scanner' }).getByRole('button', { name: 'trivy' })
  await shot('settings-tall', { pop: settingsBox, trivy, scanner: settingsBox.getByRole('group', { name: 'Scanner' }) })
  await hoverShot('settings-tall', trivy)
  await trivy.click()
  await settle()
  await pickFilter(settingsBox, 'Severity', 'high', 'nsf')
  const apply = settingsBox.getByRole('button', { name: 'Apply' })
  await shot('settings-set', { pop: settingsBox, filters: settingsBox.locator('.filter-bar'), apply })
  await hoverShot('settings-set', apply)
  await apply.click()
  await loaded()
  const nsFilterBtn = tab(panels[2]).locator('.pf-btn')
  await shot('applied', { panel: tab(panels[2]), pinned: tab(panels[2]).locator('.dash-pinned'), filterBtn: nsFilterBtn })
  await hoverShot('applied', nsFilterBtn)
  await nsFilterBtn.click()
  await settle()
  const pfPop = popover('Panel filters')
  await shot('filter-list', { pop: pfPop, list: pfPop.locator('.pf-list'), open: pfPop.getByRole('button', { name: 'Open in Findings' }) })
  await page.keyboard.press('Escape')
  await settle()

  // 5. Triage activity and its own filters
  await shot('triage-start', { addPanel })
  await hoverShot('triage-start', addPanel)
  await addFromCatalog('Triage activity', 'ta')
  const taSettings = page.getByRole('button', { name: 'Settings of Triage activity', exact: true })
  await shot('ta-settings-btn', { settings: taSettings, panel: tab('Triage activity') })
  await hoverShot('ta-settings-btn', taSettings)
  await taSettings.click()
  const taBox = popover('Panel settings')
  await taBox.waitFor({ timeout: 10000 })
  await settle()
  await pickFilter(taBox, 'User', 'lead', 'taf')
  const taApply = taBox.getByRole('button', { name: 'Apply' })
  await shot('ta-set', { pop: taBox, filters: taBox.locator('.filter-bar'), apply: taApply })
  await hoverShot('ta-set', taApply)
  await taApply.click()
  await loaded()

  // 6. delete a panel with its bin icon
  const removeSummary = page.getByRole('button', { name: `Delete ${panels[0]}`, exact: true })
  await shot('before-remove', { remove: removeSummary, panel: tab(panels[0]) })
  await hoverShot('before-remove', removeSummary)
  await removeSummary.click()
  await loaded()

  // 7. save, the details again, exit edit
  const saveBtn = page.getByRole('button', { name: 'Save changes' })
  const discard = page.getByRole('button', { name: 'Discard' })
  await shot('removed', { grid, save: saveBtn, discard, bar: page.locator('.dash-save') })
  await hoverShot('removed', saveBtn)
  await saveBtn.click()
  await page.waitForFunction(() => !document.querySelector('.dash-save button:not([disabled])'), null, { timeout: 15000 }).catch(() => {})
  await loaded()
  const details = headBtn('Name and sharing')
  await shot('saved', { bar: page.locator('.dash-save'), details })
  await hoverShot('saved', details)
  await details.click()
  await dialog().waitFor({ timeout: 10000 })
  await settle()
  await shot('details-edit', { dialog: dialog() })
  await page.keyboard.press('Escape')
  await dialog().waitFor({ state: 'detached', timeout: 10000 })
  await settle()
  const exit = headBtn('Exit edit')
  await shot('exit', { exit })
  await hoverShot('exit', exit)
  await exit.click()
  await headBtn('Edit dashboard').waitFor({ timeout: 15000 })
  await loaded()

  // 8. the read page, the scanner switch, and the pinned panel
  const scannerSwitch = head().getByRole('group', { name: 'Scanner' })
  const grype = scannerSwitch.getByRole('button', { name: 'grype' })
  await shot('read', { page: page.locator('.screen').first(), switch: scannerSwitch, grype })
  await hoverShot('read', grype)
  await grype.click()
  await loaded()
  await shot('read-grype', { switch: scannerSwitch, pinned: readPanel('top-components'), other: readPanel('findings-by-namespace') })
  const allScanners = scannerSwitch.getByRole('button', { name: 'All scanners' })
  await allScanners.click()
  await loaded()

  // the filter buttons of the read page open the matching rows
  const readNsFilter = readPanel('top-components').locator('.pf-btn')
  await shot('read-all', { filterBtn: readNsFilter })
  await hoverShot('read-all', readNsFilter)
  await readNsFilter.click()
  await settle()
  const readPop = popover('Panel filters')
  const openFindings = readPop.getByRole('button', { name: 'Open in Findings' })
  await shot('read-filters', { pop: readPop, open: openFindings })
  await hoverShot('read-filters', openFindings)
  await openFindings.click()
  await page.waitForSelector('table tbody tr', { timeout: 20000 })
  await settle()
  await shot('findings', { bar: page.locator('.filter-bar').first(), table: page.locator('table').first() })
  await page.goto(`${dashUrl}?cluster=prod-eu-1`)
  await headBtn('Edit dashboard').waitFor({ timeout: 15000 })
  await loaded()
  const taFilter = readPanel('triage-activity').locator('.pf-btn')
  await shot('read-back', { filterBtn: taFilter, panel: readPanel('triage-activity') })
  await hoverShot('read-back', taFilter)
  await taFilter.click()
  await settle()
  const taPop = popover('Panel filters')
  const openAudit = taPop.getByRole('button', { name: 'Open in Audit log' })
  await shot('ta-filters', { pop: taPop, open: openAudit })
  await hoverShot('ta-filters', openAudit)
  await openAudit.click()
  await page.waitForSelector('table tbody tr', { timeout: 20000 })
  await settle()
  await shot('audit', { bar: page.locator('.filter-bar').first(), table: page.locator('table').first() })
  await page.goto(`${dashUrl}?cluster=prod-eu-1`)
  await headBtn('Edit dashboard').waitFor({ timeout: 15000 })
  await loaded()

  // 9. export the dashboard, then import the file as a copy
  const exportBtn = headBtn('Export')
  await shot('read-export', { exportBtn })
  await hoverShot('read-export', exportBtn)
  const download = page.waitForEvent('download')
  await exportBtn.click()
  fs.mkdirSync(STATE, { recursive: true })
  const file = path.join(STATE, 'v7-dashboard.ndjson')
  await (await download).saveAs(file)
  await settle()
  await page.goto(`${BASE}/dashboards?cluster=prod-eu-1`)
  await page.getByRole('heading', { name: 'Dashboards' }).waitFor({ timeout: 20000 })
  await settle()
  const exportAll = headBtn('Export all')
  const importBtn = headBtn('Import')
  await shot('list-one', { card: card(dashId), exportAll, importBtn })
  await hoverShot('list-one', importBtn)
  await importBtn.click()
  await dialog().waitFor({ timeout: 10000 })
  await settle()
  const choose = dialog().getByRole('button', { name: 'Choose a file' })
  await shot('import', { dialog: dialog(), choose })
  await hoverShot('import', choose)
  await dialog().locator('.imp-input').setInputFiles(file)
  await settle()
  const ids = dialog().getByRole('group', { name: 'IDs' })
  const copies = ids.getByRole('button', { name: 'Make copies' })
  await shot('import-file', { dialog: dialog(), ids, copies })
  await hoverShot('import-file', copies)
  await copies.click()
  await settle()
  const runImport = dialog().getByRole('button', { name: 'Import', exact: true })
  await shot('import-copy', { dialog: dialog(), run: runImport })
  await hoverShot('import-copy', runImport)
  await runImport.click()
  await dialog().getByRole('status').waitFor({ timeout: 15000 })
  await settle()
  const done = dialog().getByRole('button', { name: 'Done' })
  await shot('imported', { dialog: dialog(), sum: dialog().getByRole('status'), done })
  await hoverShot('imported', done)
  await done.click()
  await dialog().waitFor({ state: 'detached', timeout: 10000 })
  await settle()

  // 10. delete the copy: open it, Edit dashboard, Delete, Delete dashboard
  const copyCard = page.locator('.view-card').filter({ hasNot: page.locator(`a[href="/dashboards/${dashId}"]`) }).filter({ hasText: NAME }).first()
  const copyLink = copyCard.locator('.vc-link')
  await shot('list-two', { copy: copyCard, grid: page.locator('.views-grid') })
  await hoverShot('list-two', copyLink)
  await copyLink.click()
  await headBtn('Edit dashboard').waitFor({ timeout: 15000 })
  await loaded()
  const edit = headBtn('Edit dashboard')
  await shot('copy', { edit })
  await hoverShot('copy', edit)
  await edit.click()
  await headBtn('Delete').waitFor({ timeout: 15000 })
  await loaded()
  const remove = headBtn('Delete')
  await shot('copy-edit', { remove })
  await hoverShot('copy-edit', remove)
  await remove.click()
  await dialog().waitFor({ timeout: 10000 })
  await settle()
  const confirm = dialog().getByRole('button', { name: 'Delete dashboard' })
  await shot('remove', { dialog: dialog(), confirm })
  await hoverShot('remove', confirm)
  await confirm.click()
  await page.getByRole('heading', { name: 'Dashboards' }).waitFor({ timeout: 20000 })
  await settle()
  await shot('list-after', { card: card(dashId) })

  // 11. a viewer sees the dashboard, and cannot change it
  page = await switchUser('viewer')
  await page.goto(`${dashUrl}?cluster=prod-eu-1`)
  await page.getByRole('button', { name: 'Edit dashboard' }).waitFor({ timeout: 20000 })
  await loaded()
  await shot('viewer', { edit: page.getByRole('button', { name: 'Edit dashboard' }), note: page.locator('#no-edit-note') })
}, { view: VIEW })
